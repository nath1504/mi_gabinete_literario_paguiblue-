-- =====================================================
-- LITERARIA PINGÜINO
-- Base de datos PostgreSQL para Supabase
-- =====================================================

CREATE TABLE IF NOT EXISTS public.items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (
        kind IN (
            'novela',
            'poema',
            'imagen',
            'booktrailer',
            'playlist',
            'sonido',
            'video'
        )
    ),
    description TEXT DEFAULT '',
    body TEXT DEFAULT '',
    stored_name TEXT DEFAULT '',
    original_name TEXT DEFAULT '',
    external_url TEXT DEFAULT '',
    created_at TEXT NOT NULL
);

-- =====================================================
-- CAPÍTULOS
-- =====================================================

CREATE TABLE IF NOT EXISTS public.chapters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    novel_id BIGINT NOT NULL
        REFERENCES public.items(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    body TEXT DEFAULT '',
    chapter_number INTEGER NOT NULL,
    created_at TEXT NOT NULL,
    UNIQUE (novel_id, chapter_number)
);

-- =====================================================
-- BIBLIOTECA PERSONAL
-- =====================================================

CREATE TABLE IF NOT EXISTS public.books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    author TEXT DEFAULT '',
    rating TEXT DEFAULT '',
    shelf_code TEXT DEFAULT '',
    edition TEXT DEFAULT '',
    publisher TEXT DEFAULT '',
    status TEXT DEFAULT 'Pendiente',
    tags TEXT DEFAULT '',
    start_date TEXT DEFAULT '',
    finish_date TEXT DEFAULT '',
    publication_date TEXT DEFAULT '',
    format TEXT DEFAULT 'Físico',
    genre TEXT DEFAULT '',
    isbn TEXT DEFAULT '',
    saga_type TEXT DEFAULT 'Libro único',
    saga_title TEXT DEFAULT '',
    chapter_count TEXT DEFAULT '',
    pages TEXT DEFAULT '',
    price TEXT DEFAULT '',
    subgenre TEXT DEFAULT '',
    themes TEXT DEFAULT '',
    review TEXT DEFAULT '',
    synopsis TEXT DEFAULT '',
    opinion TEXT DEFAULT '',
    favorite_quotes TEXT DEFAULT '',
    playlist TEXT DEFAULT '',
    characters TEXT DEFAULT '',
    moments TEXT DEFAULT '',
    cover_name TEXT DEFAULT '',
    cover_original TEXT DEFAULT '',
    created_at TEXT NOT NULL
);

-- =====================================================
-- AUTENTICACIÓN DE ADMINISTRACIÓN
-- =====================================================

CREATE TABLE IF NOT EXISTS public.admin_auth (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    username TEXT NOT NULL,
    password_hash TEXT NOT NULL
);

-- =====================================================
-- AUTENTICACIÓN DEL DIARIO PRIVADO
-- =====================================================

CREATE TABLE IF NOT EXISTS public.diary_auth (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    password_hash TEXT NOT NULL
);

-- =====================================================
-- ENTRADAS DEL DIARIO
-- =====================================================

CREATE TABLE IF NOT EXISTS public.diary_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    mood TEXT DEFAULT '',
    entry_date DATE NOT NULL DEFAULT CURRENT_DATE,
    content TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP NOT NULL DEFAULT NOW()
);

-- =====================================================
-- ÍNDICES PARA MEJORAR LAS CONSULTAS
-- =====================================================

CREATE INDEX IF NOT EXISTS idx_items_kind
    ON public.items(kind);

CREATE INDEX IF NOT EXISTS idx_items_title
    ON public.items(title);

CREATE INDEX IF NOT EXISTS idx_chapters_novel
    ON public.chapters(novel_id, chapter_number);

CREATE INDEX IF NOT EXISTS idx_books_title
    ON public.books(title);

CREATE INDEX IF NOT EXISTS idx_books_status
    ON public.books(status);

CREATE INDEX IF NOT EXISTS idx_diary_date
    ON public.diary_entries(entry_date DESC);

-- =====================================================
-- SEGURIDAD: ROW LEVEL SECURITY
-- =====================================================

ALTER TABLE public.items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.chapters ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.books ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin_auth ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.diary_auth ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.diary_entries ENABLE ROW LEVEL SECURITY;

